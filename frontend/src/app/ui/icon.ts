/** An icon as a complete <svg> string, for markup Angular does not render (Leaflet's marker icons). */
export function iconSvg(name: string, size = 20): string {
  if (!Object.hasOwn(ICONS, name)) {
    return '';
  }
  return (
    `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" ` +
    `stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false" ` +
    `width="${size}" height="${size}">${ICONS[name]}</svg>`
  );
}

/** A 24x24 outline icon; an unknown name renders nothing. */
@Component({
  selector: 'app-icon',
  template: `
    @if (markup(); as inner) {
      <svg
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        stroke-width="1.75"
        stroke-linecap="round"
        stroke-linejoin="round"
        aria-hidden="true"
        focusable="false"
        [attr.width]="size()"
        [attr.height]="size()"
        [innerHTML]="inner"
      ></svg>
    }
  `,
  styles: `
    :host {
      display: inline-flex;
      flex: none;
      line-height: 0;
    }
  `,
})
export class Icon {
  readonly name = input.required<string>();
  readonly size = input(20);

  private readonly sanitizer = inject(DomSanitizer);

  // The markup comes from the constant table above, never from user input, so it is
  // safe to trust. (Angular's HTML sanitizer would strip the SVG children.)
  protected readonly markup = computed<SafeHtml | null>(() => {
    const name = this.name();
    return Object.hasOwn(ICONS, name) ? this.sanitizer.bypassSecurityTrustHtml(ICONS[name]) : null;
  });
}
